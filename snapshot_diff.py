#!/usr/bin/env python3
"""Build an aggregate-only Pages diff from current public data and the local published history."""
import argparse
import json
import subprocess
import tempfile
from datetime import datetime
from pathlib import Path

PUBLIC_DATA = 'docs/data.json'
PUBLIC_DIFF = 'docs/snapshot-diff.json'
UTC = '%Y-%m-%d %H:%M UTC'


def _snap(doc):
    if not isinstance(doc, dict):
        raise ValueError('invalid public snapshot')
    ts = doc['generated']
    stamp = datetime.strptime(ts, UTC)
    if stamp.strftime(UTC) != ts:
        raise ValueError('noncanonical batch timestamp')
    wazuh = doc['wazuh']
    metrics = {
        'alerts_7d': wazuh['total_7d'],
        'misp_ip_attributes': doc['misp']['total'],
        'watchlist': doc['blocklist_n'],
        'outside_top_500_alerts': wazuh['pipeline_24h_coverage']['outside_top_alerts'],
    }
    is_count = lambda n: type(n) is int and 0 <= n <= (1 << 53) - 1
    if not all(n is None or is_count(n) for n in metrics.values()):
        raise ValueError('invalid public counts')
    rows = wazuh['top_src']
    if not isinstance(rows, list) or len(rows) > 20:
        raise ValueError('invalid public rows')
    sources = {}
    for row in rows:
        if (not isinstance(row, list) or len(row) != 2 or not isinstance(row[0], str)
                or row[0] in sources or not is_count(row[1])):
            raise ValueError('invalid public row')
        sources[row[0]] = row[1]
    return stamp, metrics, sources


def compare(before, after):
    current, new_metrics, new_rows = _snap(after)
    result = {'schema_version': 1, 'current_utc': after['generated'], 'previous_utc': None,
              'metrics': None, 'sources': None}
    if before is None or 'public_revision' in after:
        return result
    older, old_metrics, old_rows = _snap(before)
    if older >= current:
        raise ValueError('baseline not earlier than current batch')
    common = old_rows.keys() & new_rows.keys()
    result.update(previous_utc=before['generated'],
                  metrics={key: [old_metrics[key], n] for key, n in new_metrics.items()},
                  sources={'entered': len(new_rows.keys() - old_rows.keys()),
                           'left': len(old_rows.keys() - new_rows.keys()),
                           'retained': len(common),
                           'changed_alert_counts': sum(old_rows[ip] != new_rows[ip] for ip in common)})
    return result  # No addresses, raw observations, status reasons or free text are serialized.


def git(repo, *args):
    return subprocess.check_output(['git', *args], cwd=repo, stderr=subprocess.DEVNULL,
                                   timeout=10)


def build(repo):
    after = json.loads((repo / PUBLIC_DATA).read_bytes())
    curr, _, _ = _snap(after)
    before = None
    if 'public_revision' not in after:
        # Skip heartbeat-only commits and display edits for the same batch. Bound
        # history scanning; no distinct comparable baseline means unavailable.
        revisions = git(repo, 'log', '--first-parent', '-12', '--format=%H', 'HEAD', '--', PUBLIC_DATA)
        for revision in revisions.decode('ascii').splitlines():
            try:
                candidate = json.loads(git(repo, 'show', f'{revision}:{PUBLIC_DATA}'))
                older, _, _ = _snap(candidate)
            except (KeyError, TypeError, ValueError, subprocess.CalledProcessError):
                break  # Do not skip a malformed published batch and call an older one consecutive.
            if older < curr:
                before = candidate
                break
            if older > curr:
                raise ValueError('public snapshot timestamp regressed')
    return (json.dumps(compare(before, after), indent=2) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify the diff without writing it')
    args = parser.parse_args()
    repo = Path(__file__).resolve().parent
    dest = repo / PUBLIC_DIFF
    try:
        payload = build(repo)
        if args.check:
            if dest.read_bytes() != payload:
                raise ValueError('stored diff differs')
        else:
            # Publish only generated bytes; never stage a previously edited working copy.
            with tempfile.NamedTemporaryFile(dir=dest.parent, delete=False) as tmp:
                tmp_path = Path(tmp.name)
                try:
                    tmp.write(payload)
                    tmp.flush()
                    tmp_path.chmod(0o644)  # This artifact is already a public aggregate.
                    tmp_path.replace(dest)
                finally:
                    tmp_path.unlink(missing_ok=True)
    except (OSError, KeyError, TypeError, ValueError, subprocess.SubprocessError):
        parser.exit(1, 'Public snapshot diff unavailable or not current; no diff published\n')


if __name__ == '__main__':
    main()
