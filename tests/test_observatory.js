'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const dir=path.join(__dirname,'../docs');
const read=name=>fs.readFileSync(path.join(dir,name),'utf8');
const data=JSON.parse(read('command-center-data.json'));
const model=require('../docs/observatory.js');
const graph=model.buildGraph(data);
assert.equal(graph.nodes.length,12);
assert.equal(graph.edges.length,14);
assert.equal(new Set(graph.nodes.map(n=>n.id)).size,graph.nodes.length);
for(const edge of graph.edges){assert(graph.nodes.some(n=>n.id===edge.from));assert(graph.nodes.some(n=>n.id===edge.to));assert.notEqual(edge.from,edge.to);}
assert(graph.nodes.some(n=>n.id==='rag'&&n.state==='attention'));
assert(graph.nodes.some(n=>n.id==='clickhouse'&&n.state==='stale'));
const markup=read('observatory.html');
const script=read('observatory.js');
const ids=[...markup.matchAll(/\bid="([^"]+)"/g)].map(([,v])=>v);
assert.equal(ids.length,new Set(ids).size);
for(const id of script.matchAll(/byId\("([^"]+)"\)/g))assert(ids.includes(id[1]),`missing DOM id ${id[1]}`);
assert.match(markup,/connect-src 'self'/);
assert.doesNotMatch(markup,/unsafe-inline/);
assert.doesNotMatch(script,/innerHTML/);
assert.match(markup,/vendor\/three\.min\.js/);
assert(fs.existsSync(path.join(dir,'vendor/three.min.js')));
assert(fs.existsSync(path.join(dir,'vendor/THREE-LICENSE.txt')));
const publicText=markup+'\n'+script+'\n'+JSON.stringify(graph);
assert.doesNotMatch(publicText,/\b(?:\d{1,3}\.){3}\d{1,3}\b/);
assert.doesNotMatch(publicText,/\b(?:kit-lab|debian)\b/i);
assert.doesNotMatch(publicText,/gho_[A-Za-z0-9]+|Pwdn0|ELASTIC_PASSWORD=/i);
assert.match(read('command-center.html'),/href="observatory\.html">3D observatory/);
console.log('Observatory: graph integrity, CSP, DOM ids, local Three.js and public privacy checks passed');
