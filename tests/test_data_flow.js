'use strict';
const assert=require('node:assert/strict');const vm=require('node:vm');const fs=require('node:fs');const path=require('node:path');
const dir=path.join(__dirname,'../docs'),read=name=>fs.readFileSync(path.join(dir,name),'utf8');
const script=read('data-flow.js'),markup=read('data-flow.html'),ctx=vm.createContext({});
vm.runInContext(read('public-view.js')+'\n'+script,ctx);
const model=vm.runInContext('DataFlow',ctx),ids=new Set(model.nodes.map(n=>n[0]));
assert.deepEqual([...model.layers],['Collection','Enrichment','Action']);
assert.equal(ids.size,model.nodes.length);
assert.equal(new Set(model.edges.map(([a,b])=>`${a}:${b}`)).size,model.edges.length);
assert(model.edges.every(([a,b,k,title])=>a!==b&&ids.has(a)&&ids.has(b)&&['run','review'].includes(k)&&title));
assert(model.nodes.every(([id,l,title,short,note,boundary])=>model.layers[l]&&title&&short&&note&&boundary&&model.neighbors(id).size>1));
assert(model.neighbors('indexer').has('store')&&model.neighbors('misp').has('cross'));
assert(!model.edges.some(([a,b])=>a==='cidrs'&&['misp','release','vt','pages'].includes(b)));
assert(!model.edges.some(([a,b])=>a==='analyst'&&['misp','pages','vt'].includes(b)));
assert(model.edges.filter(e=>e[1]==='vt').every(e=>e[0]==='release'));
assert.match(model.heartbeat({schema_version:1,state:'ok',last_attempt_utc:'2026-11-26 22:00 UTC'},Date.parse('2026-11-27T12:35Z')),/schedule overdue.*Not per-service status/);
assert.match(model.heartbeat(null,Date.now()),/unavailable/);
assert.match(model.heartbeat({schema_version:1,state:'ok',last_attempt_utc:'2028-01-01 22:00 UTC'},Date.parse('2026-11-27T22:01Z')),/unavailable/);
assert.match(markup,/connect-src 'self'/);assert.doesNotMatch(markup,/unsafe-inline/);assert.doesNotMatch(script,/innerHTML/);
assert.deepEqual([...script.matchAll(/\bfetch\('([^']+)'/g)].map(m=>m[1]),['status.json']);
for(const page of ['index.html','classic.html','flow.html'])assert.match(read(page),/href="data-flow.html">Data flow/);
console.log('Data flow: valid graph endpoints, private/output boundaries, route and heartbeat scope checks');
